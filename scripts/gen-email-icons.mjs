// Generates email social icons: PNGs in public/email/ plus lib/email/icons.ts
// with base64 content for inline CID attachments. Emails can't use
// react-icons components, so we rasterize them once here.
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import { FaLinkedinIn, FaGithub, FaXTwitter } from 'react-icons/fa6'
import { FiBriefcase } from 'react-icons/fi'
import { LuFlaskConical } from 'react-icons/lu'
import sharp from 'sharp'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'

const COLOR = '#94a3b8' // slate-400: reads as quiet on the emails' dark navy card
const SIZE = 64 // rendered 2x+ for retina; displayed at ~22px

const icons = [
  { name: 'linkedin', Component: FaLinkedinIn },
  { name: 'github', Component: FaGithub },
  { name: 'x', Component: FaXTwitter },
]

mkdirSync('public/email', { recursive: true })

const entries = []
for (const { name, Component } of icons) {
  const svg = renderToStaticMarkup(createElement(Component, { size: SIZE }))
    .replace(/currentColor/g, COLOR)
  const path = `public/email/${name}.png`
  await sharp(Buffer.from(svg)).resize(SIZE, SIZE).png().toFile(path)
  entries.push(`  ${name}: '${readFileSync(path).toString('base64')}',`)
  console.log(`wrote ${path}`)
}

// The N8 mark for the emails' header, from the site's tab icon.
await sharp('public/tab/n8-icon-192.png').resize(96, 96).png().toFile('public/email/logo.png')
entries.push(`  logo: '${readFileSync('public/email/logo.png').toString('base64')}',`)
console.log('wrote public/email/logo.png')

// The auto-reply's "While you wait" cards: matching rounded tiles (navy, a
// thin border) like the N8 mark, each with its place's icon.
const TILE = 96
const tile = (inner) => `<svg xmlns="http://www.w3.org/2000/svg" width="${TILE}" height="${TILE}" viewBox="0 0 ${TILE} ${TILE}">
  <rect x="1.5" y="1.5" width="${TILE - 3}" height="${TILE - 3}" rx="22" fill="#0e1b30" stroke="#24406a" stroke-width="3"/>${inner}</svg>`
const glyph = (Component, size, color) =>
  renderToStaticMarkup(createElement(Component, { size, color }))
    .replace('<svg ', `<svg x="${(TILE - size) / 2}" y="${(TILE - size) / 2}" `)
// The Lab's flask, with its bubbles caught mid-rise (the site animates them).
const bubbles = [[43, 61], [52, 56], [47.5, 50]].map(([cx, cy], i) => `<circle cx="${cx}" cy="${cy}" r="${3 - i * 0.6}" fill="#22d3ee"/>`).join('')
const appturnity = readFileSync('public/brands/appturnity.png').toString('base64')
const tiles = {
  lab: tile(glyph(LuFlaskConical, 52, '#22d3ee') + bubbles),
  portfolio: tile(glyph(FiBriefcase, 46, '#7dd3fc')),
  appturnity: tile(`<image x="27" y="23" width="42" height="49" href="data:image/png;base64,${appturnity}"/>`),
}
for (const [name, svg] of Object.entries(tiles)) {
  const path = `public/email/${name}.png`
  await sharp(Buffer.from(svg)).png().toFile(path)
  entries.push(`  ${name}: '${readFileSync(path).toString('base64')}',`)
  console.log(`wrote ${path}`)
}

writeFileSync(
  'lib/email/icons.ts',
  `// Generated by scripts/gen-email-icons.mjs - do not edit by hand.
// Base64 PNGs attached to outgoing mail as inline CID images, so the
// icons render without depending on the site being deployed or on the
// client loading remote images.
export const EMAIL_ICONS: Record<'linkedin' | 'github' | 'x' | 'logo' | 'lab' | 'portfolio' | 'appturnity', string> = {
${entries.join('\n')}
}
`
)
console.log('wrote lib/email/icons.ts')
