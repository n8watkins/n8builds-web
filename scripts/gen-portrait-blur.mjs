// Makes the hero portrait's blur placeholder from the photo itself
// (components/sections/heroPortraitBlur.ts): a 12px-wide, tiny JPEG, inlined as a data URL,
// so the circle shows a soft version of the real portrait while the photo loads, never
// black. Run after the portrait changes: node scripts/gen-portrait-blur.mjs
import { writeFileSync } from 'node:fs'
import sharp from 'sharp'

const buf = await sharp('public/hero/portrait.jpg').resize(12, 12, { fit: 'cover' }).jpeg({ quality: 60 }).toBuffer()
const out = `// Generated by scripts/gen-portrait-blur.mjs from public/hero/portrait.jpg. Do not edit by hand.
export const PORTRAIT_BLUR = 'data:image/jpeg;base64,${buf.toString('base64')}'
`
writeFileSync('components/sections/heroPortraitBlur.ts', out)
console.log(`${buf.length} bytes`)
